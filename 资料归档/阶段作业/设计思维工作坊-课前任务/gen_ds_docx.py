def run(p, text, size=10.5, bold=False, color=None, italic=False):
    r = p.add_run(text)
    r.font.name = '微软雅黑'; r.font.size = Pt(size); r.font.bold = bold; r.font.italic = italic
    r._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    if color is not None: r.font.color.rgb = color
    return r

def P(text="", size=10.5, bold=False, color=None, align=None, before=2, after=4, indent=None):
    p = doc.add_paragraph()
    if align is not None: p.alignment = align
    pf = p.paragraph_format; pf.space_before = Pt(before); pf.space_after = Pt(after)
    if indent: pf.left_indent = Pt(indent)
    if text: run(p, text, size=size, bold=bold, color=color)
    return p

def H1(text, page=False):
    p = P(text, size=14, bold=True, color=BLUE, before=14, after=6)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr'); e = OxmlElement('w:bottom')
    e.set(qn('w:val'), 'single'); e.set(qn('w:sz'), '8'); e.set(qn('w:color'), '2E4A8F')
    pBdr.append(e); pPr.append(pBdr)
    if page: doc.add_page_break()
    return p

