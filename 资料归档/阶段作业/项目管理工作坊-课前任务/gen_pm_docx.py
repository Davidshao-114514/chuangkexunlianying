def run(p, text, size=10.5, bold=False, color=None, italic=False):
    r = p.add_run(text)
    r.font.name = '微软雅黑'; r.font.size = Pt(size); r.font.bold = bold; r.font.italic = italic
    r._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    if color is not None: r.font.color.rgb = color
    return r

def P(text="", size=10.5, bold=False, color=None, align=None, before=2, after=4, indent=None):
    p = doc.add_paragraph()
    if align is not None: p.alignment = align
    pf = p.paragraph_format; pf.space_before = Pt(before); pf.space_after = Pt(after)
    if indent: pf.left_indent = Pt(indent)
    if text: run(p, text, size=size, bold=bold, color=color)
    return p

def H1(text, page=False):
    p = P(text, size=14, bold=True, color=BLUE, before=14, after=6)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr'); e = OxmlElement('w:bottom')
    e.set(qn('w:val'), 'single'); e.set(qn('w:sz'), '8'); e.set(qn('w:color'), '2E4A8F')
    pBdr.append(e); pPr.append(pBdr)
    if page: doc.add_page_break()
    return p

def H2(text):
    return P(text, size=12, bold=True, color=BLUE, before=10, after=4)

def H3(text):
    return P(text, size=10.5, bold=True, before=6, after=3)

def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd'); shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)

def table(headers, rows, widths=None, fsize=9.5, header_fill='D9E2F3'):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        c = t.cell(0, j); c.text = ''
        p = c.paragraphs[0]; p.paragraph_format.space_after = Pt(1)
        run(p, h, size=fsize, bold=True)
        shade(c, header_fill)
    for i, row in enumerate(rows, start=1):
        for j, v in enumerate(row):
            c = t.cell(i, j); c.text = ''
            p = c.paragraphs[0]; p.paragraph_format.space_after = Pt(1)
            run(p, v, size=fsize)
    if widths:
        for j, w in enumerate(widths):
            for i in range(len(rows) + 1):
                t.cell(i, j).width = Cm(w)
    P("", after=4)
    return t

