def table(headers, rows, cw=None, fsize=8.5, header_fill="D9E2F3", row_fills=None, widths_cm=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, htxt in enumerate(headers):
        c = t.cell(0, j); c.text = ""
        run(c.paragraphs[0], htxt, size=fsize, bold=True)
        c.paragraphs[0].paragraph_format.space_after = Pt(0)
        shade(c, header_fill)
    for i, row in enumerate(rows, start=1):
        for j, v in enumerate(row):
            c = t.cell(i, j); c.text = ""
            r0 = run(c.paragraphs[0], str(v), size=fsize)
            c.paragraphs[0].paragraph_format.space_after = Pt(0)
            if row_fills and row_fills.get(i - 1):
                shade(c, row_fills[i - 1])
    if widths_cm:
        for j, w in enumerate(widths_cm):
            for i in range(len(rows) + 1):
                t.cell(i, j).width = Cm(w)
    para("", size=6, space_after=2)
    return t


